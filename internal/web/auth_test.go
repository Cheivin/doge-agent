package web

import (
	"strings"
	"testing"
)

func TestGenerateToken(t *testing.T) {
	a, err := generateToken()
	if err != nil {
		t.Fatal(err)
	}
	if len(a) != 64 { // 32 bytes hex
		t.Fatalf("token length = %d", len(a))
	}
	b, _ := generateToken()
	if a == b {
		t.Fatal("tokens should differ")
	}
}

func TestLoginFlow(t *testing.T) {
	a, err := newAuthState("sekrit")
	if err != nil {
		t.Fatal(err)
	}
	if a.Token() != "sekrit" {
		t.Fatalf("token = %q", a.Token())
	}

	if _, ok := a.login("wrong"); ok {
		t.Fatal("wrong token accepted")
	}
	value, ok := a.login("sekrit")
	if !ok {
		t.Fatal("correct token rejected")
	}
	if value == "" {
		t.Fatal("empty cookie value")
	}
	if !a.authenticated(value) {
		t.Fatal("issued session should be valid")
	}
	if a.authenticated("not-a-session") {
		t.Fatal("random cookie accepted")
	}
	a.logout(value)
	if a.authenticated(value) {
		t.Fatal("session should be revoked after logout")
	}
}

func TestAutoGeneratedToken(t *testing.T) {
	a, err := newAuthState("")
	if err != nil {
		t.Fatal(err)
	}
	if len(a.Token()) != 64 {
		t.Fatalf("auto token length = %d", len(a.Token()))
	}
}

func TestConstantTimeCompareRejectsSimilar(t *testing.T) {
	a, _ := newAuthState(strings.Repeat("a", 40))
	candidate := strings.Repeat("a", 39) + "b"
	if _, ok := a.login(candidate); ok {
		t.Fatal("near-miss token accepted")
	}
}
